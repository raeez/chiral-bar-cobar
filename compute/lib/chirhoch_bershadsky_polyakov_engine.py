r"""Typed audit surface for Bershadsky--Polyakov chiral cohomology.

The Bershadsky--Polyakov algebra is the minimal (equivalently,
subregular) Drinfeld--Sokolov reduction of ``sl_3``.  In the standard
Fehily--Kawasetsu--Ridout conformal presentation it is an ordinary
bosonic vertex algebra strongly generated by

``J`` (weight 1), ``G+`` and ``G-`` (weight 3/2), and ``T`` (weight 2).

The primary-source central charge is

    c_BP(k) = -(2k+3)(3k+1)/(k+3),

and the level involution ``k -> -k-6`` gives the exact identity
``c_BP(k)+c_BP(-k-6)=50``.  These facts determine neither the modular
characteristic nor chiral Hochschild cohomology.

This module computes the data that follow directly from the OPE and
records the comparison problems.  In particular:

* ``J_(0)`` implements charge rotation, hence that candidate derivation
  is inner;
* scaling ``J`` violates the fixed scalar product
  ``J_(1)J=(2k+3)/3`` at generic level;
* a complete classification of generator-compatible derivations remains
  open;
* the generic centre, same-family bar duality, bounded-to-chiral comparison,
  and Theorem-H support statement remain open;
* chart-level Betti and Hilbert fields remain ``None`` pending those maps.

Numeric entry points for unproved invariants raise
``UnverifiedBPChirHochError``.  Status-report entry points return ``None``
together with the exact resolution obligation.
"""

