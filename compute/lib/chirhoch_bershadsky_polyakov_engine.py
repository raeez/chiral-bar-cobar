@dataclass(frozen=True)
class BPDerivationAnalysis:
    """Exact candidate tests and the remaining derivation obligation."""

    total_outer: Optional[int]
    j_current_contribution: Optional[int]
    c_deformation_contribution: Optional[int]
    fermionic_contribution: Optional[int]
    inner_derivations: List[str]
    exact_candidate_tests: Dict[str, bool] = field(default_factory=dict)
    unresolved_candidates: Dict[str, str] = field(default_factory=dict)
    degree_2_product_lanes: Dict[str, str] = field(default_factory=dict)
    status: str = "open-complete-derivation-complex"

    @property
    def dim_chirhoch1(self) -> Optional[int]:
        return self.total_outer


def derivation_analysis_bp(level: Any = None) -> BPDerivationAnalysis:
    r"""Test the two derivation candidates decided by the primary OPE.

    Charge rotation is the inner zero mode ``J_(0)``.  For a putative
    scaling derivation ``D(J)=J``, applying ``D`` to
    ``J_(1)J=(2k+3)/3`` gives ``0=2(2k+3)/3``.  This rules out the
    candidate whenever ``2k+3`` is invertible.  The test becomes
    inconclusive at ``k=-3/2`` and the full derivation classification
    remains open at every level until the linearized Borcherds system is
    computed.
    """

    lev = _level(level)
    j_level = simplify((2 * lev + 3) / 3)
    generic_scaling_obstruction = simplify(2 * j_level)
    return BPDerivationAnalysis(
        total_outer=None,
        j_current_contribution=None,
        c_deformation_contribution=None,
        fermionic_contribution=None,
        inner_derivations=["J_{(0)} (charge rotation)"],
        exact_candidate_tests={
            "J_charge_rotation_is_inner": True,
            "J_scaling_fails_when_2k_plus_3_invertible": (
                generic_scaling_obstruction != 0
                if lev.is_number
                else True
            ),
            "all_strong_generators_are_even": all(
                datum["parity"] == 0 for datum in BP_GENERATORS.values()
            ),
        },
        unresolved_candidates={
            "complete_even_derivation_system": (
                "solve the linearized Borcherds identities on J,G+,G-,T "
                "modulo all inner zero modes"
            ),
            "exceptional_J_level_zero": (
                "repeat the derivation computation at k=-3/2 using the mixed G+G- OPE"
            ),
        },
        degree_2_product_lanes={
            "level_motion": "exact one-parameter OPE family; cohomology class placement open",
            "modular_kappa": BP_KAPPA_STATUS.status,
        },
    )


@dataclass(frozen=True)
class BPHochschildPolynomial:
    """Status-typed BP chiral Hochschild polynomial."""

    p0: Optional[int]
    p1: Optional[int]
    p2: Optional[int]
    status: str
    resolution_obligation: str

    @property
    def coefficients(self) -> List[Optional[int]]:
        return [self.p0, self.p1, self.p2]

    @property
    def total_dimension(self) -> Optional[int]:
        if None in self.coefficients:
            return None
        return int(sum(self.coefficients))

    @property
    def euler_characteristic(self) -> Optional[int]:
        if None in self.coefficients:
            return None
        return int(self.p0 - self.p1 + self.p2)

    @property
    def is_palindromic(self) -> Optional[bool]:
        if self.p0 is None or self.p2 is None:
            return None
        return self.p0 == self.p2

    def evaluate(self, value: Any) -> Any:
        if None in self.coefficients:
            _raise_open("P_BP(t)")
        return self.p0 + self.p1 * value + self.p2 * value * value


