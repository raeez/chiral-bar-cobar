State = Tuple[Tuple[int, ...], Tuple[int, ...]]
VACUUM: State = ((), ())

H_BAR = (
    "H_W3^bar: an ordered Fulton--MacPherson residue complex, orientation convention, completion, and d^2 proof"
)


class OpenW3ExtendedBarError(RuntimeError):
    """Signals that PBW/OPE data have reached the bar boundary."""


@dataclass(frozen=True)
class ClaimPacket:
    statement: str
    status: str
    value: object | None = None
    hypotheses: Tuple[str, ...] = ()


def _open(statement: str) -> ClaimPacket:
    return ClaimPacket(statement, "open", None, (H_BAR,))


def state_weight(state: State) -> int:
    return sum(state[0]) + sum(state[1])


def make_state(l_modes: Tuple[int, ...], w_modes: Tuple[int, ...]) -> State:
    return tuple(sorted(l_modes, reverse=True)), tuple(sorted(w_modes, reverse=True))


def _partitions_into_parts_geq(n: int, min_part: int) -> List[Tuple[int, ...]]:
    if n == 0:
        return [()]
    if n < min_part:
        return []
    result: List[Tuple[int, ...]] = []

    def build(remaining: int, largest: int, current: List[int]):
        if remaining == 0:
            result.append(tuple(current))
            return
        for part in range(min(remaining, largest), min_part - 1, -1):
            build(remaining - part, part, current + [part])

    build(n, n, [])
    return result


def vbar_basis(max_weight: int) -> Dict[int, List[State]]:
    """Enumerate the generic freely generated augmentation-ideal PBW basis."""

    basis: Dict[int, List[State]] = {0: []}
    for weight in range(1, max_weight + 1):
        states = []
        for l_weight in range(weight + 1):
            w_weight = weight - l_weight
            for l_partition in _partitions_into_parts_geq(l_weight, 2):
                for w_partition in _partitions_into_parts_geq(w_weight, 3):
                    state = (l_partition, w_partition)
                    if state != VACUUM:
                        states.append(state)
        basis[weight] = states
    return basis


def dim_vbar(h: int) -> int:
    return len(vbar_basis(max(0, h)).get(h, []))


def dim_vbar_gf(max_h: int) -> Dict[int, int]:
    """Compute PBW dimensions by the independent product expansion."""

    coefficients = [0] * (max_h + 1)
    coefficients[0] = 1
    for weight in range(2, max_h + 1):
        for degree in range(weight, max_h + 1):
            coefficients[degree] += coefficients[degree - weight]
    for weight in range(3, max_h + 1):
        for degree in range(weight, max_h + 1):
            coefficients[degree] += coefficients[degree - weight]
    coefficients[0] -= 1
    return {weight: coefficients[weight] for weight in range(max_h + 1)}


def ordered_top_form_chain_dim(arity: int, weight: int) -> int:
    r"""Count ``Vbar^tensor arity tensor OS^(arity-1)_top`` dimensions."""

    if arity < 1 or weight < 2 * arity:
        return 0
    dims = dim_vbar_gf(weight)
    convolution = {0: 1}
    for _ in range(arity):
        next_convolution: Dict[int, int] = {}
        for left_weight, left_count in convolution.items():
            for right_weight in range(2, weight - left_weight + 1):
                value = dims.get(right_weight, 0)
                if value:
                    total = left_weight + right_weight
                    if total <= weight:
                        next_convolution[total] = next_convolution.get(total, 0) + left_count * value
        convolution = next_convolution
    return convolution.get(weight, 0) * factorial(arity - 1)


def bar_chain_dim(n: int, h: int, vbar_dims: Optional[Dict[int, int]] = None, max_h: int = 30) -> int:
    """Compatibility name for the raw top-form chain count with arity ``n+1``."""

    return ordered_top_form_chain_dim(n + 1, h)


def bar_chain_table(max_n: int, max_h: int) -> Dict[Tuple[int, int], int]:
    return {
        (degree, weight): value
        for degree in range(max_n + 1)
        for weight in range(max_h + 1)
        if (value := bar_chain_dim(degree, weight))
    }


class W3VacuumModule:
    """Finite generic PBW presentation with exact generator-level OPE actions."""

    def __init__(self, max_weight: int, c_val=sp.Symbol("c")):
        self.max_weight = max_weight
        self.c_val = sp.sympify(c_val)
        basis = vbar_basis(max_weight)
        self._all_states = [VACUUM] + [state for weight in range(max_weight + 1) for state in basis.get(weight, [])]
        self._state_to_idx = {state: index for index, state in enumerate(self._all_states)}
        self._vbar_states = self._all_states[1:]
        self._vbar_to_idx = {state: index for index, state in enumerate(self._vbar_states)}
        self.total_dim = len(self._all_states)

    def vbar_states_at_weight(self, weight: int) -> List[State]:
        return [state for state in self._vbar_states if state_weight(state) == weight]

    def _L_on_state(self, mode: int, state: State) -> Dict[State, object]:
        if mode == 0:
            return {} if state == VACUUM else {state: sp.Integer(state_weight(state))}
        if state == VACUUM and mode <= -2:
            target = make_state((-mode,), ())
            return {target: sp.Integer(1)} if target in self._state_to_idx else {}
        if state == VACUUM and mode >= -1:
            return {}
        raise OpenW3ExtendedBarError(
            "General Virasoro-mode action requires a completed quotient presentation beyond the finite PBW ledger."
        )

    def _W_on_state(self, mode: int, state: State) -> Dict[State, object]:
        if state == VACUUM and mode <= -3:
            target = make_state((), (-mode,))
            return {target: sp.Integer(1)} if target in self._state_to_idx else {}
        if state == VACUUM and mode >= -2:
            return {}
        raise OpenW3ExtendedBarError(
            "General W-mode action requires the nonlinear mode-algebra quotient beyond the finite PBW ledger."
        )

    def _add_state(self, vector: List[object], state: State, coefficient) -> None:
        index = self._state_to_idx.get(state)
        if index is not None:
            vector[index] = sp.simplify(vector[index] + coefficient)

    def compute_nth_product(self, a: State, b: State, n: int) -> List[object]:
        generator_names = {make_state((2,), ()): "T", make_state((), (3,)): "W"}
        if a not in generator_names or b not in generator_names:
            raise OpenW3ExtendedBarError(
                "Nth products on composite PBW states require the nonlinear quotient presentation."
            )
        packet = w3_nth_product(generator_names[a], generator_names[b], n)
        c_symbol = sp.Symbol("c")
        vector: List[object] = [sp.Integer(0)] * self.total_dim
        for field, coefficient in packet.items():
            coefficient = sp.simplify(sp.sympify(coefficient).subs(c_symbol, self.c_val))
            if field == "vac":
                vector[0] += coefficient
            elif field == "T":
                self._add_state(vector, make_state((2,), ()), coefficient)
            elif field == "dT":
                self._add_state(vector, make_state((3,), ()), coefficient)
            elif field == "W":
                self._add_state(vector, make_state((), (3,)), coefficient)
            elif field == "dW":
                self._add_state(vector, make_state((), (4,)), coefficient)
            elif field == "d2T":
                self._add_state(vector, make_state((4,), ()), 2 * coefficient)
            elif field == "Lambda":
                self._add_state(vector, make_state((2, 2), ()), coefficient)
                self._add_state(vector, make_state((4,), ()), -sp.Rational(3, 5) * coefficient)
            elif field == "d3T":
                self._add_state(vector, make_state((5,), ()), 6 * coefficient)
            elif field == "dLambda":
                self._add_state(vector, make_state((3, 2), ()), 2 * coefficient)
                self._add_state(vector, make_state((5,), ()), -sp.Rational(4, 5) * coefficient)
        return vector

    def compute_mu(self, a: State, b: State):
        raise OpenW3ExtendedBarError(
            "A residue multiplication cannot be obtained by summing singular nth products; it awaits H_W3^bar."
        )


def verify_mu_generators(c_val=7, verbose: bool = True) -> Dict[str, bool]:
    """Compatibility verifier for the separated generator OPE packet."""

    c_value = sp.sympify(c_val)
    c_symbol = sp.Symbol("c")
    products = w3_nth_products()
    alpha = sp.Integer(32) / (22 + 5 * c_symbol)
    checks = {
        "TT leading norm = c/2": products[("T", "T")][3]["vac"] == c_symbol / 2,
        "TW primary action": products[("T", "W")][1]["W"] == 3,
        "WT skew derivative": products[("W", "T")][0]["dW"] == 2,
        "WW leading norm = c/3": products[("W", "W")][5]["vac"] == c_symbol / 3,
        "WW pole-two Lambda = 32/(22+5c)": sp.simplify(products[("W", "W")][1]["Lambda"] - alpha) == 0,
        "WW pole-one dLambda = 16/(22+5c)": sp.simplify(products[("W", "W")][0]["dLambda"] - alpha / 2) == 0,
    }
    if verbose:
        print(checks)
    return checks


def verify_skew_symmetry(c_val=7) -> Dict[str, bool]:
    products = w3_nth_products()
    return {
        "W_(1)T = T_(1)W": products[("W", "T")][1] == products[("T", "W")][1],
        "W_(0)T = 2dW": products[("W", "T")][0] == {"dW": 2},
    }


