"""Tests for genus-1 PBW degeneration in the Virasoro family."""

from sympy import Rational, Symbol, eye

from compute.lib.virasoro_pbw_genus1 import (
    VirasoroVacuumModule,
    verify_global_sl2_relations,
    verify_l0_scalar_action,
    verify_quartic_pole,
    verify_virasoro_pbw_genus1,
    verify_weight_dimensions,
    vir_pbw_basis,
    weight_space_dimension,
)


class TestPBWBasis:
    """PBW basis of the Virasoro vacuum module."""

    def test_low_weight_basis(self):
        assert vir_pbw_basis(2) == [(2,)]
        assert vir_pbw_basis(3) == [(3,)]
        assert vir_pbw_basis(4) == [(4,), (2, 2)]

    def test_weight_space_dimensions(self):
        expected = {
            2: 1,
            3: 1,
            4: 2,
            5: 2,
            6: 4,
            7: 4,
            8: 7,
            9: 8,
            10: 12,
        }
        for weight, dim in expected.items():
            assert weight_space_dimension(weight) == dim

    def test_dimension_verification_bundle(self):
        for ok in verify_weight_dimensions(10).values():
            assert ok


class TestGlobalConformalModes:
    """The global conformal sl_2 generated by L_-1, L_0, L_1."""

    def test_l0_is_scalar_on_weight_spaces(self):
        module = VirasoroVacuumModule(max_weight=10)
        for weight in range(2, 11):
            l0 = module.mode_matrix(0, weight)
            assert l0 == weight * eye(l0.rows)
            assert l0.rank() == l0.rows

    def test_l1_annihilates_T(self):
        module = VirasoroVacuumModule(max_weight=4)
        l1_on_t = module.mode_matrix(1, 2)
        assert l1_on_t.shape == (0, 1)

    def test_l0_on_T(self):
        module = VirasoroVacuumModule(max_weight=4)
        l0_on_t = module.mode_matrix(0, 2)
        assert l0_on_t.shape == (1, 1)
        assert l0_on_t[0, 0] == Rational(2)

    def test_sl2_relations(self):
        for ok in verify_global_sl2_relations(10).values():
            assert ok

    def test_l0_scalar_bundle(self):
        for ok in verify_l0_scalar_action(10).values():
            assert ok


class TestQuarticPole:
    """The quartic pole is present but not needed for the PBW kill mechanism."""

    def test_t3_t(self):
        c = Symbol("c")
        module = VirasoroVacuumModule(central_charge=c, max_weight=4)
        t3 = module.stress_tensor_product_matrix(3, 2)
        assert t3.shape == (1, 1)
        assert t3[0, 0] == c / 2

    def test_quartic_verification_bundle(self):
        for ok in verify_quartic_pole().values():
            assert ok


class TestIntegration:
    """End-to-end verification bundle used by the manuscript theorem."""

    def test_all_pass(self):
        for name, ok in verify_virasoro_pbw_genus1(10).items():
            assert ok, name
