"""Primary-source regression tests for Bershadsky--Polyakov diagnostics.

Source convention: Fehily--Kawasetsu--Ridout, CMP 385 (2021),
Definition 2.1, Eq. (2.2), and Proposition 2.2.  Their ``BP^k`` is an
ordinary vertex operator algebra, freely strongly generated by the even
fields ``J,G^+,G^-,L`` of weights ``1,3/2,3/2,2``.  The tests therefore use
bosonic mode factors and ordinary vertex-algebra skew-symmetry.

The initial character coefficients are checked both against a hardcoded
PBW monomial census and against an independent coloured-partition oracle.
Genus-one ``kappa`` values are tested only through their open status.
"""

