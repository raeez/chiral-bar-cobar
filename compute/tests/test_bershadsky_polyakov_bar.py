k = Symbol("k")
fs = bp_primary_ope_normal_form(k)


def _independent_bosonic_character(max_weight: int):
    """Coloured-partition expansion derived directly from FKR weights."""

    max_half = 2 * max_weight
    coefficients = [0] * (max_half + 1)
    coefficients[0] = 1

    # Each tuple is (first mode weight in half-units, step, number of colours).
    # J: 1,2,...; G+,G-: 3/2,5/2,...; L: 2,3,... .
    mode_families = ((2, 2, 1), (3, 2, 2), (4, 2, 1))
    for first, step, colours in mode_families:
        for mode_weight in range(first, max_half + 1, step):
            for _colour in range(colours):
                for degree in range(mode_weight, max_half + 1):
                    coefficients[degree] += coefficients[degree - mode_weight]

    return {
        Rational(index, 2): coefficient
        for index, coefficient in enumerate(coefficients)
        if index > 0 and coefficient
    }


class TestFKRConvention:
    def test_four_even_strong_generators(self):
        assert tuple(GENERATOR_NAMES) == ("J", "G+", "G-", "T")
        assert all(data["parity"] == 0 for data in GENERATORS.values())
        assert [GENERATORS[name]["weight"] for name in GENERATOR_NAMES] == [
            Rational(1),
            Rational(3, 2),
            Rational(3, 2),
            Rational(2),
        ]

    def test_charges_are_independent_of_parity(self):
        assert GENERATORS["J"]["charge"] == 0
        assert GENERATORS["G+"]["charge"] == 1
        assert GENERATORS["G-"]["charge"] == -1
        assert GENERATORS["T"]["charge"] == 0

    def test_standard_central_charge_is_fkr_equation_2_2(self):
        expected = -(2 * k + 3) * (3 * k + 1) / (k + 3)
        assert simplify(bp_central_charge(k) - expected) == 0
        assert simplify(bp_central_charge(0) + 1) == 0
        assert simplify(bp_central_charge(1) + 5) == 0
        assert simplify(bp_central_charge(Rational(-3, 2))) == 0

    def test_standard_companion_sum_is_50(self):
        assert simplify(bp_koszul_conductor() - 50) == 0
        for level in (0, 1, 2, Rational(-1, 2), 5):
            companion = bp_dual_level(level)
            assert simplify(
                bp_central_charge(level) + bp_central_charge(companion) - 50
            ) == 0

    def test_shifted_formula_is_separate(self):
        shifted = 2 - 24 * (k + 1) ** 2 / (k + 3)
        assert simplify(bp_shifted_central_charge(k) - shifted) == 0
        assert simplify(bp_shifted_koszul_conductor() - 196) == 0
        assert simplify(bp_shifted_central_charge(k) - bp_central_charge(k)) != 0

    def test_companion_level_is_involutive(self):
        assert simplify(bp_dual_level(bp_dual_level(k)) - k) == 0


class TestFKROPEPacket:
    def test_all_ordered_generator_pairs_are_present(self):
        products = bp_nth_products()
        assert set(products) == {
            (left, right) for left in GENERATOR_NAMES for right in GENERATOR_NAMES
        }

    def test_virasoro_and_current_coefficients(self):
        assert simplify(
            bp_nth_product("T", "T", 3)["vac"] - bp_central_charge(k) / 2
        ) == 0
        assert bp_nth_product("T", "T", 1) == {"T": Rational(2)}
        assert bp_nth_product("T", "T", 0) == {"dT": Rational(1)}
        assert simplify(
            bp_nth_product("J", "J", 1)["vac"] - (2 * k + 3) / 3
        ) == 0

    def test_primary_weights_and_charges(self):
        assert bp_nth_product("T", "J", 1) == {"J": Rational(1)}
        assert bp_nth_product("T", "G+", 1) == {"G+": Rational(3, 2)}
        assert bp_nth_product("T", "G-", 1) == {"G-": Rational(3, 2)}
        assert bp_nth_product("J", "G+", 0) == {"G+": Rational(1)}
        assert bp_nth_product("J", "G-", 0) == {"G-": Rational(-1)}

    def test_forward_charged_ope_matches_fkr(self):
        assert simplify(
            bp_nth_product("G+", "G-", 2)["vac"]
            - (k + 1) * (2 * k + 3)
        ) == 0
        assert simplify(
            bp_nth_product("G+", "G-", 1)["J"] - 3 * (k + 1)
        ) == 0
        simple = bp_nth_product("G+", "G-", 0)
        assert simple["JJ"] == 3
        assert simplify(simple["dJ"] - Rational(3, 2) * (k + 1)) == 0
        assert simplify(simple["T"] + k + 3) == 0

    def test_reverse_charged_ope_uses_ordinary_skew_symmetry(self):
        leading = bp_nth_product("G-", "G+", 2)
        double = bp_nth_product("G-", "G+", 1)
        simple = bp_nth_product("G-", "G+", 0)
        assert simplify(leading["vac"] + (k + 1) * (2 * k + 3)) == 0
        assert simplify(double["J"] - 3 * (k + 1)) == 0
        assert simple["JJ"] == -3
        assert simplify(simple["dJ"] - Rational(3, 2) * (k + 1)) == 0
        assert simplify(simple["T"] - (k + 3)) == 0

    def test_same_charge_singular_opes_vanish_by_charge(self):
        assert bp_nth_product("G+", "G+", 0) == {}
        assert bp_nth_products()[("G+", "G+")] == {}
        assert bp_nth_products()[("G-", "G-")] == {}

    def test_other_reverse_pairs(self):
        assert bp_nth_product("G+", "T", 1) == {"G+": Rational(3, 2)}
        assert bp_nth_product("G+", "T", 0) == {"dG+": Rational(1, 2)}
        assert bp_nth_product("G-", "T", 0) == {"dG-": Rational(1, 2)}
        assert bp_nth_product("G+", "J", 0) == {"G+": Rational(-1)}
        assert bp_nth_product("G-", "J", 0) == {"G-": Rational(1)}

    def test_all_implemented_skew_relations(self):
        assert all(verify_skew_symmetry().values())


class TestOPECoefficientPackets:
    def test_tt_and_jj_packets(self):
        tt_vac, tt_bar1 = bp_bar_diff_deg2("T", "T")
        jj_vac, jj_bar1 = bp_bar_diff_deg2("J", "J")
        assert simplify(tt_vac["vac"] - bp_central_charge(k) / 2) == 0
        assert tt_bar1["T"] == 2
        assert simplify(jj_vac["vac"] - fs["J_level"]) == 0
        assert jj_bar1 == {}

    def test_charged_packets_retain_order(self):
        forward_vac, forward = bp_bar_diff_deg2("G+", "G-")
        reverse_vac, reverse = bp_bar_diff_deg2("G-", "G+")
        assert simplify(forward_vac["vac"] + reverse_vac["vac"]) == 0
        assert simplify(forward["J"] - reverse["J"]) == 0
        assert forward["JJ"] == -reverse["JJ"]
        assert simplify(forward["T"] + reverse["T"]) == 0

    def test_all_sixteen_packets_exist(self):
        assert len(bp_bar_diff_deg2_all()) == 16

    def test_leading_pole_curvatures_are_exact_ope_data(self):
        curvature = bp_curvature()
        assert simplify(curvature["T"] - bp_central_charge(k) / 2) == 0
        assert simplify(curvature["J"] - fs["J_level"]) == 0
        assert simplify(curvature["G+G-"] - fs["G_pairing"]) == 0


